def gen_music():
    o = ['// GENERATED by tools/gen/gen_audio.py - do not edit', '#pragma once', '#include <stdint.h>', '',
         '// Themes composed for Tamanimals, as note events for gbsynth.cpp.', '',
         'struct MusicNote {', '  uint16_t freq;   // synth frequency register, 0 = rest', '  uint8_t duty;', '  uint8_t vol;', '  int8_t envDir;', '  uint8_t envPeriod;', '  uint16_t ms;', '};', '']
    tbl = []
    for name, lead, bass, beat, title in TRACKS:
        a = voice(lead, beat, 2, 11, 4)
        b = voice(bass, beat, 1, 8, 2)
        for ch, notes in (('CH1', a), ('CH2', b)):
            o.append(f'static const MusicNote MUSIC_{name}_{ch}[{len(notes)}] = {{')
            o += [f'  {{ {f}, {d}, {v}, {e}, {p}, {ms} }},' for f, d, v, e, p, ms in notes]
            o += ['};', '']
        tbl.append(f'  {{ MUSIC_{name}_CH1, sizeof(MUSIC_{name}_CH1)/sizeof(MusicNote), MUSIC_{name}_CH2, sizeof(MUSIC_{name}_CH2)/sizeof(MusicNote), "{title}" }},')
    o += ['struct MusicTrack {', '  const MusicNote *ch1; uint16_t n1;', '  const MusicNote *ch2; uint16_t n2;', '  const char *name;', '};',
          f'#define MUSIC_TRACKS {len(TRACKS)}', 'static const MusicTrack MUSIC_TBL[MUSIC_TRACKS] = {'] + tbl + ['};', '']
    with open(os.path.join(ROOT, 'music.h'), 'w', newline='\n') as f:
        f.write('\n'.join(o))
    print('wrote music.h')


# Calls by body plan: (note hz, duty, vol, env dir, env period, frames) on the first voice; the second
# voice follows a little below, and a noise channel adds breath where the animal needs it.
def sweep(a, b, n, frames, duty=2, vol=12, decay=2):
    out = []
    for i in range(n):
        f = a * (b / a) ** (i / max(1, n - 1))
        out.append((reg(f), duty, vol, -1, decay, frames))
    return out



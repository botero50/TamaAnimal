SEMI = {'C': 0, 'C#': 1, 'D': 2, 'D#': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'G#': 8, 'A': 9, 'A#': 10, 'B': 11}


def hz(note):
    name, oct_ = note[:-1], int(note[-1])
    return 440.0 * 2 ** ((SEMI[name] + 12 * (oct_ + 1) - 69) / 12)


def reg(freq):
    """Synth units: Hz = 131072 / (2048 - f)."""
    return max(0, min(2047, int(round(2048 - 131072 / freq))))


def voice(score, beat_ms, duty, vol, env_period):
    """score: 'A4:2 R:1 ...' with lengths in beats (fractions allowed)."""
    out = []
    for tok in score.split():
        n, _, ln = tok.partition(':')
        ms = int(float(ln or 1) * beat_ms)
        if n == 'R':
            out.append((0, duty, 0, 0, 0, ms))
        else:
            out.append((reg(hz(n)), duty, vol, -1, env_period, ms))
    return out



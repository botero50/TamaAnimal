def gen_cries():
    names = list(CALLS)
    o = ['// GENERATED by tools/gen/gen_audio.py - do not edit', '#pragma once', '#include <stdint.h>', '',
         '// Animal calls synthesised for Tamanimals, as note events for gbsynth.cpp.', '',
         'struct CryNote {', '  uint16_t freq;     // pulse: synth frequency register; noise: samples per LFSR clock', '  uint8_t duty;', '  uint8_t vol;', '  int8_t envDir;', '  uint8_t envPeriod;',
         '  uint8_t frames;    // length in 1/59.73 s, before the species length modifier', '};', '']
    tbl = []
    for i, name in enumerate(names):
        parts = CALLS[name]
        refs = []
        for suffix, notes in zip('PQN', parts):
            if notes:
                o.append(f'static const CryNote CRY_{i:02d}_{suffix}[{len(notes)}] = {{  // {name}')
                o += [f'  {{ {f}, {d}, {v}, {e}, {p}, {fr} }},' for f, d, v, e, p, fr in notes]
                o += ['};', '']
                refs.append(f'CRY_{i:02d}_{suffix}, {len(notes)}')
            else:
                refs.append('nullptr, 0')
        tbl.append('  { ' + ', '.join(refs) + ', -1, -1 },')
    o += ['struct CryBase {', '  const CryNote *p1; uint8_t n1;', '  const CryNote *p2; uint8_t n2;', '  const CryNote *nz; uint8_t nn;', '  int16_t set1, set2;   // -1, or a pitch that replaces the species pitch', '};',
          f'#define CRY_BASES {len(names)}', 'static const CryBase CRY_BASE_TBL[CRY_BASES] = {'] + tbl + ['};', '', 'struct CryMon { uint16_t base; int16_t pitch; uint16_t tempo; };',
          f'#define CRY_DEX {len(ANIMALS)}', '', 'static const CryMon CRY_MON[CRY_DEX] = {']
    for a in ANIMALS:
        h = zlib.crc32(a['name'].encode())
        base = names.index(ARCH_CALL[a['arch']])
        # bigger animals lower and longer; every species a little different
        size = {1: 40, 2: 0, 3: -30, 4: -70}[a['rarity']]
        pitch = (h % 121 - 60) + size
        tempo = 200 + ((h >> 8) & 0x7F)
        o.append(f'  {{ {base}, {pitch}, {tempo} }},  // {a["id"]} {a["name"]}')
    o += ['};', '']
    with open(os.path.join(ROOT, 'cries.h'), 'w', newline='\n') as f:
        f.write('\n'.join(o))
    print('wrote cries.h')



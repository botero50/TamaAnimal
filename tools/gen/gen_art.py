W, H = 240, 112


class Scene:
    def __init__(self, seed):
        self.r = random.Random(seed)
        self.px = [[(0, 0, 0)] * W for _ in range(H)]

    def sky(self, top, bot, horizon=H, bands=9):
        for y in range(horizon):
            t = y / max(1, horizon - 1)
            k = t * (bands - 1)
            lo = int(k)
            fr = k - lo
            for x in range(W):
                j = lo + (1 if fr > .5 + .25 * (((x ^ y) & 1) * 2 - 1) else 0)
                j = min(bands - 1, j) / (bands - 1)
                self.px[y][x] = tuple(int(top[i] + (bot[i] - top[i]) * j) for i in range(3))

    def fill(self, y0, col, y1=H, x0=0, x1=W):
        for y in range(max(0, y0), min(H, y1)):
            for x in range(max(0, x0), min(W, x1)):
                self.px[y][x] = col

    def ridge(self, base, amp, freq, col, shade=None, seed=0):
        ph = [self.r.random() * 6 for _ in range(4)]
        for x in range(W):
            h = sum(math.sin(x * freq * f + ph[i]) * amp / (i + 1) for i, f in enumerate((1, 2.3, 4.7, 9.1)))
            top = int(base + h)
            for y in range(max(0, top), H):
                dark = shade and y - top < 3
                self.px[y][x] = shade if dark else col

    def circle(self, cx, cy, rad, col):
        for y in range(max(0, cy - rad), min(H, cy + rad + 1)):
            for x in range(max(0, cx - rad), min(W, cx + rad + 1)):
                if (x - cx) ** 2 + (y - cy) ** 2 <= rad * rad:
                    self.px[y][x] = col

    def speckle(self, y0, y1, col, n):
        for _ in range(n):
            self.px[self.r.randrange(y0, y1)][self.r.randrange(W)] = col

    def tuft(self, x, y, col, h=5):
        for i in range(h):
            for dx in (-(h - i) // 2, 0, (h - i) // 2):
                if 0 <= x + dx < W and 0 <= y - i < H:
                    self.px[y - i][x + dx] = col

    def tree(self, x, y, trunk, leaf, leaf2, s=1.0):
        self.fill(int(y - 16 * s), trunk, y, x - int(2 * s), x + int(2 * s) + 1)
        for dx, dy, rad in ((0, -24, 11), (-8, -18, 8), (8, -18, 8)):
            self.circle(x + int(dx * s), y + int(dy * s), int(rad * s), leaf)
        self.circle(x - int(2 * s), y - int(26 * s), int(5 * s), leaf2)

    def pine(self, x, y, col, snow=None, s=1.0):
        for tier in range(3):
            top = y - int((18 + tier * 10) * s)
            wd = int((11 - tier * 2.5) * s)
            hgt = int(13 * s)
            for i in range(hgt):
                half = wd * i // hgt
                c = snow if snow and i < 3 else col
                self.fill(top + i, c, top + i + 1, x - half, x + half + 1)
        self.fill(y - int(6 * s), (84, 56, 36), y, x - 1, x + 2)

    def indexed(self):
        pal, idx, seen = [], [], {}
        for row in self.px:
            for p in row:
                v = rgb(p)
                if v not in seen:
                    seen[v] = len(pal)
                    pal.append(v)
                idx.append(seen[v])
        assert len(pal) < 256, len(pal)
        return pal, idx


def night(col):
    return tuple(int(c * f) for c, f in zip(col, (.38, .42, .68)))


def scene(biome, is_night, seed):
    s = Scene(seed * 7 + is_night)
    t = night if is_night else (lambda c: c)
    sky_top = {0: (118, 196, 240), 1: (96, 190, 246), 2: (150, 214, 226), 3: (238, 150, 96), 4: (130, 186, 232), 5: (192, 222, 244)}[biome]
    sky_bot = {0: (216, 240, 244), 1: (232, 244, 236), 2: (222, 240, 214), 3: (250, 214, 150), 4: (222, 236, 244), 5: (238, 246, 250)}[biome]
    if is_night:
        s.sky((20, 26, 62), (58, 62, 112), 74)
        s.speckle(0, 44, (236, 236, 250), 46)
        s.circle(190, 20, 9, (240, 236, 200))
        s.circle(194, 17, 8, s.px[17][208])
    else:
        s.sky(sky_top, sky_bot, 74)
        s.circle(46, 22, 10, (255, 244, 188))
        for cx, cy in ((110, 18), (172, 28), (214, 14)):
            for dx in (-10, 0, 10):
                s.circle(cx + dx, cy, 6 if dx else 8, (250, 252, 254))
    if biome == 0:   # savanna meadow
        s.ridge(58, 4, .03, t((168, 196, 120)))
        s.ridge(68, 3, .05, t((142, 182, 92)))
        s.fill(74, t((122, 176, 78)))
        s.ridge(84, 2, .06, t((104, 158, 66)), t((122, 176, 78)))
        for x in (34, 196):
            s.fill(50, t((96, 70, 44)), 72, x - 1, x + 2)
            for dx in range(-16, 17):
                s.fill(47 + abs(dx) // 6, t((88, 138, 62)), 54 - abs(dx) // 5, x + dx, x + dx + 1)
        for _ in range(38):
            s.tuft(s.r.randrange(W), s.r.randrange(82, H), t((74, 132, 54)), s.r.randrange(3, 7))
    elif biome == 1:   # coast
        s.fill(58, t((58, 150, 206)), 84)
        for y in range(60, 84, 5):
            for x in range(s.r.randrange(9), W, 22):
                s.fill(y, t((168, 222, 240)), y + 1, x, x + 8)
        s.ridge(84, 3, .03, t((238, 214, 160)), t((250, 240, 214)))
        s.speckle(90, H, t((208, 180, 128)), 180)
        for x in (24, 214):
            s.fill(48, t((120, 86, 56)), 92, x, x + 3)
            for a in range(0, 360, 50):
                dx, dy = math.cos(math.radians(a)) * 16, math.sin(math.radians(a)) * 6 + 3
                for k in range(16):
                    s.circle(x + 1 + int(dx * k / 16), 47 + int(dy * k / 16), 2, t((70, 150, 80)))
    elif biome == 2:   # jungle
        s.fill(40, t((96, 160, 112)))

def art_rows(rows):
    return '\n'.join(f'  "{r}",' for r in rows)


def gen_species():
    p = os.path.join(ROOT, 'species.h')
    s = open(p, encoding='utf-8').read()
    # the nine starter drawings: everything between the palette and the first icon
    m = re.search(r'static const char\* const SPR_LION\[32\].*?(?=static const char\* const SPR_ICON_PILL)', s, flags=re.S)
    assert m
    blocks, rows = [], []
    for name, arch, _ty in STARTERS:
        g = sl.draw(name, arch, {}, size=32)
        lines = [''.join(c or '.' for c in r) for r in g]
        blocks.append(f'static const char* const SPR_{name}[32] = {{  // 32x32\n' + art_rows(lines) + '\n};\n')
    s = s[:m.start()] + '\n'.join(blocks) + '\n' + s[m.end():]
    for name, rows, cols in (('SPR_BALL_POKE', POUCH, 'rry'), ('SPR_BALL_GREAT', POUCH, 'BNb'), ('SPR_BALL_ULTRA', POUCH, 'SkY')):
        art = [r.replace('X', cols[0]).replace('Y', cols[1]).replace('W', cols[2]) for r in rows]
        s, n = re.subn(rf'(static const char\* const {name}\[16\] = \{{[^\n]*\n).*?(\n\}};)', lambda mm: mm.group(1) + art_rows(art) + mm.group(2), s, flags=re.S)
        assert n == 1, name
    s, n = re.subn(r'(static const char\* const SPR_ICON_PLAY\[16\] = \{[^\n]*\n).*?(\n\};)', lambda mm: mm.group(1) + art_rows(PAW_ICON) + mm.group(2), s, flags=re.S)
    assert n == 1
    # table
    cols = {'STRENGTH': 'TYPE_STRENGTH', 'SPEED': 'TYPE_SPEED', 'INTELLIGENCE': 'TYPE_INTELLIGENCE'}
    acc = {'STRENGTH': 0xC186, 'SPEED': 0xFD20, 'INTELLIGENCE': 0xA254}
    rows = []
    for name, arch, ty in STARTERS:
        a = sl.look(name, arch)
        col = sl.rgb565(sl.PAL[a['col']])
        rows.append(f'  {{ "{name}", {cols[ty]}, SPR_{name}, 5, -1, 0, 8, 22, 25, 11, 25, 0x{col:04X}, 0x{acc[ty]:04X} }},')
    s, n = re.subn(r'(static const Species SPECIES\[NUM_SPECIES\] = \{\n).*?(\n\};)', lambda mm: mm.group(1) + '\n'.join(rows) + mm.group(2), s, flags=re.S)
    assert n == 1
    s = s.replace('// GENERATED by tools/sprites.py - edit there and run:\n//   python3 tools/sprites.py emit\n', '// The nine starters here are drawn by tools/gen/gen_art.py; the icons are hand-drawn pixel maps.\n')
    with open(p, 'w', newline='\n', encoding='utf-8') as f:
        f.write(s)
    print('patched species.h')



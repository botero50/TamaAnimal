def arena(name, seed):
    wall, wall2, floor = ARENA_STYLE[name]
    s = Scene(100 + seed)
    s.sky(wall, wall2, 46, 5)
    if name in ('ROCK', 'FIRE'):
        for y in range(4, 46, 8):
            for x in range((y // 8 % 2) * 12, W, 24):
                s.fill(y, wall2, y + 1, x, x + 22)
                s.fill(y, wall2, y + 8, x, x + 1)
    elif name == 'WATER':
        for y in range(10, 46, 9):
            for x in range(s.r.randrange(9), W, 18):
                s.fill(y, (250, 252, 254), y + 1, x, x + 7)
    elif name == 'ELECTRIC':
        for x in range(14, W, 30):
            s.circle(x, 14, 4, (250, 228, 120))
        s.fill(36, (230, 190, 70), 39)
    elif name == 'GRASS':
        for x in range(0, W, 13):
            s.circle(x, 42, 9, (78, 138, 74))
            s.circle(x + 5, 34, 6, (102, 164, 86))
    elif name == 'GHOST':
        s.speckle(0, 44, (214, 204, 240), 60)
        s.circle(196, 16, 8, (232, 226, 190))
    elif name == 'ICE':
        for x in range(4, W, 15):
            n = s.r.randrange(5, 15)
            for i in range(n):
                s.fill(i, (240, 250, 254), i + 1, x, x + max(1, 7 - i // 2))
    else:
        for x in (36, 120, 204):
            s.fill(0, (120, 118, 130), 46, x - 7, x + 8)
            s.fill(0, (160, 158, 168), 46, x - 7, x - 3)
    # a perspective floor with a paw print in the middle: this game's own ring
    for y in range(46, H):
        t = (y - 46) / (H - 46)
        shade = 1 - .14 * (1 - t)
        for x in range(W):
            checker = ((int((x - W / 2) / (10 + t * 18)) + (y - 46) // (4 + int(t * 8))) & 1)
            k = shade * (1.0 if checker else .93)
            s.px[y][x] = tuple(int(c * k) for c in floor)
    accent = {'ROCK': (240, 216, 170), 'WATER': (250, 252, 254), 'ELECTRIC': (250, 220, 100), 'GRASS': (240, 248, 214), 'FIRE': (250, 180, 90),
              'GHOST': (190, 170, 240), 'ICE': (120, 184, 226), 'DRAGON': (226, 196, 110)}[name]
    for sx, sy, rx, ry in ((120, 86, 15, 8), (97, 72, 5, 3), (110, 66, 5, 3), (130, 66, 5, 3), (143, 72, 5, 3)):
        for y in range(sy - ry, sy + ry + 1):
            for x in range(sx - rx, sx + rx + 1):
                if ((x - sx) / rx) ** 2 + ((y - sy) / ry) ** 2 <= 1:
                    s.px[y][x] = accent
    return s


def gen_backs():
    o = ['// GENERATED by tools/gen/gen_art.py - do not edit', '#pragma once', '#include <stdint.h>', '',
         '// Battle backgrounds, 8bpp indexed with a per-image RGB565 palette, all drawn by code.',
         '// Indexed by biome (see dex.h) then 0 = day, 1 = night.', '']
    names = ['meadow', 'coast', 'jungle', 'badlands', 'mountains', 'snow']
    tbl = []

    def emit(sym, s, comment):
        pal, idx = s.indexed()
        o.append(f'// {comment}')
        o.append(f'static const uint16_t {sym}_PAL[{len(pal)}] = {{')
        for i in range(0, len(pal), 16):
            o.append('  ' + ', '.join(f'0x{v:04X}' for v in pal[i:i + 16]) + ',')
        o.extend(['};', f'static const uint8_t {sym}_IDX[{W * H}] = {{'])
        for y in range(H):
            o.append('  ' + ','.join(map(str, idx[y * W:(y + 1) * W])) + ',')
        o.extend(['};', ''])
        return len(pal)

    for b in range(6):
        row = []
        for n in range(2):
            c = emit(f'BACK_{b}_{n}', scene(b, n, b), f'{names[b]} {"night" if n else "day"}')
            row.append(f'{{ BACK_{b}_{n}_PAL, BACK_{b}_{n}_IDX, {W}, {H}, {c} }}')
        tbl.append('  { ' + ', '.join(row) + ' },')
    arenas = list(ARENA_STYLE)
    atbl = []
    for i, a in enumerate(arenas):
        c = emit(f'ARENA_{a}', arena(a, i), f'ranger arena: {a.lower()}')
        atbl.append(f'  {{ ARENA_{a}_PAL, ARENA_{a}_IDX, {W}, {H}, {c} }},')
    o += ['struct BackScene {', '  const uint16_t *pal;', '  const uint8_t *idx;', '  uint16_t w, h, palCount;', '};', '#define BACK_BIOMES 6',
          'static const BackScene BACKS[BACK_BIOMES][2] = {'] + tbl + ['};', '',
          'enum : uint8_t { ' + ', '.join('ARENA_' + a for a in arenas) + ', ARENA_COUNT };',
          'static const BackScene ARENAS[ARENA_COUNT] = {'] + atbl + ['};', '']
    text = '\n'.join(o)
    # the data arrays and the enum may not share a name
    text = re.sub(r'ARENA_(\w+)_(PAL|IDX)', r'ARENADATA_\1_\2', text)
    write('backs.h', text)



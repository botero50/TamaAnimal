def gen_logo():
    w, h = 299, 53
    px = [[0] * w for _ in range(h)]
    word = 'TAMANIMALS'
    scale = 5
    total = sum(len(FONT[c][0]) * scale + 4 for c in word) - 4
    x = (w - total) // 2
    y0 = (h - 7 * scale) // 2
    for ch in word:
        g = FONT[ch]
        for r, row in enumerate(g):
            for k, v in enumerate(row):
                if v == '#':
                    for yy in range(scale):
                        for xx in range(scale):
                            px[y0 + r * scale + yy][x + k * scale + xx] = 1 if r * scale + yy < 16 else 2
        x += len(g[0]) * scale + 4
    out = [row[:] for row in px]
    for y in range(h):
        for x in range(w):
            if px[y][x] == 0:
                for dy in range(-2, 3):
                    for dx in range(-2, 3):
                        if 0 <= y + dy < h and 0 <= x + dx < w and px[y + dy][x + dx]:
                            out[y][x] = 3
    bits = bytearray((w * h + 3) // 4)
    for y in range(h):
        for x in range(w):
            i = y * w + x
            bits[i >> 2] |= out[y][x] << ((i & 3) * 2)
    o = ['// GENERATED by tools/gen/gen_art.py - do not edit', '#pragma once', '#include <stdint.h>', f'#define LOGO_W {w}', f'#define LOGO_H {h}',
         '// 2 bits per pixel, 4 per byte, LSB first: 0 clear, 1 top colour, 2 bottom colour, 3 outline', 'static const uint8_t LOGO_BITS[] = {']
    for i in range(0, len(bits), 16):
        o.append('  ' + ', '.join(f'0x{b:02X}' for b in bits[i:i + 16]) + ',')
    o += ['};', '']
    write('logo.h', '\n'.join(o))



                y0 = top + abs(dx) * 56 // w
                s.fill(y0, t((122, 128, 144)), 76, cx + dx, cx + dx + 1)
                s.fill(y0, t((244, 248, 252)), y0 + max(0, 14 - abs(dx) // 3), cx + dx, cx + dx + 1)

def gen_badges():
    o = ['// GENERATED by tools/gen/gen_art.py - do not edit', '//', '// Ranger stamps, one set per region: an original ring and symbol for each.',
         '#pragma once', '#include <stdint.h>', '', '#define BADGE_PX 32', f'#define BADGE_REGIONS {len(RING)}', '']
    table = []
    for rn, rings in RING.items():
        row = []
        for i, (a, b) in enumerate(rings):
            c = sl.Canvas(40)
            c.f = 1
            c.n = 32
            c.g = [[None] * 32 for _ in range(32)]
            c.oval(16, 16, 14.5, 14.5, b)
            c.oval(16, 16, 12.5, 12.5, a)
            c.oval(16, 16, 10.5, 10.5, 'w')
            ink = b if b != 'y' else 'C'
            SYMBOLS[i](c, 16, 16, 1, ink)
            g = c.finish()
            used = sorted({v for r in g for v in r if v})
            assert len(used) <= 15, used
            idx = {v: n for n, v in enumerate(used)}
            name = f'BADGE_{rn}_{i}'
            o.append(f'static const uint16_t {name}_PAL[{len(used)}] = {{ ' + ', '.join(f'0x{sl.rgb565(sl.PAL[v]):04X}' for v in used) + ' };')
            o.append(f'static const uint8_t {name}_IDX[1024] = {{')
            for r in g:
                o.append('  ' + ','.join(str(idx[v]) if v else '255' for v in r) + ',')
            o += ['};', '']
            row.append(f'{{ {name}_PAL, {name}_IDX }}')
        table.append('  { ' + ', '.join(row) + ' },')
    o += ['struct BadgeArt { const uint16_t *pal; const uint8_t *idx; };', 'static const BadgeArt BADGES_ART[BADGE_REGIONS][8] = {'] + table + ['};', '']
    write('badges.h', '\n'.join(o))



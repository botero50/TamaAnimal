def gen_avatars():
    o = ['// GENERATED by tools/gen/gen_art.py - do not edit', '#pragma once', '#include <stdint.h>', '',
         '// Player avatars, drawn for this game: 16x16, 8bpp indexed with a small RGB565 palette. 0xFF is transparent.', '']
    rows = []
    for name, art, col in AVATARS:
        lines = [l for l in art.strip().split('\n')]
        assert len(lines) == 16 and all(len(l) == 16 for l in lines), name
        o.append(f'static const uint16_t AV_{name}_PAL[3] = {{ 0x18C4, 0x{col:04X}, 0xFE6F }};')
        o.append(f'static const uint8_t AV_{name}_IDX[256] = {{')
        for l in lines:
            o.append('  ' + ', '.join({'.': '0xFF', 'k': '0x00', '0': '0x00', '1': '0x01', '2': '0x02'}[ch] for ch in l) + ',')
        o += ['};', '']
        rows.append(f'  {{ AV_{name}_IDX, AV_{name}_PAL, "{name}" }},')
    o += ['struct AvatarArt {', '  const uint8_t *idx;', '  const uint16_t *pal;', '  const char *name;', '};', '#define AVATAR_PX 16', f'#define AVATAR_COUNT {len(AVATARS)}',
          'static const AvatarArt AVATARS[AVATAR_COUNT] = {'] + rows + ['};', '']
    write('avatars.h', '\n'.join(o))


